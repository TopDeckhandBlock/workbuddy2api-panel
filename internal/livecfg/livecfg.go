// Package livecfg Потокобезопасный держатель изменяемой конфигурации времени выполнения.
//
// контекст: конфигурация, загружаемая при старте процесса — обычные поля (много чтений, ноль записей), но админ-панель позволяет менять конфигурацию онлайн,
// поэтому небольшое количество"применяется на горячую"поле требует потокобезопасной точки R/W. Здесь — неизменяемый снапшот + atomic Указатель:
// Читатель Load получить консистентное представление, пишущая сторона Store Целиком замена, без блокировок и гонок данных.
//
// несёт только**Глубокий путь чтения, высокая потребность в hot-правках**немногочисленные поля; параметры пула/Параметры расписания и т.д. имеют существующие setter
// （pool.SetBreaker、scheduler.Reconfigure и т.д.), повторно сюда не включать.
package livecfg

import (
	"sync/atomic"
	"time"
)

// Snapshot Неизменяемое представление конфигурации за одно чтение.
type Snapshot struct {
	APIKey string // Шлюз/общий ключ аутентификации панели; пусто = Без аутентификации
	SoftCooldown time.Duration // 429 база мягкого кулдауна (<=0 вызывающая сторона откатывается на встроенный дефолт)
	SanitizeFingerprints bool // Десенсибилизация отпечатка тела исходящего запроса
	RecordClientInfo bool // Логировать ли в журнале запросов источник вызова (клиент IP / UA）
}

// Holder Атомарно хранит текущий снапшот.
type Holder struct {
	p atomic.Pointer[Snapshot]
}

// New Построение на основе начального снапшота.
func New(s Snapshot) *Holder {
	h := &Holder{}
	h.Store(s)
	return h
}

// Load Вернуть текущий снапшот (Holder для nil или никогда не Store возвращается zero-value снапшот, вызывающей стороне не нужна проверка на null).
func (h *Holder) Load() Snapshot {
	if h == nil {
		return Snapshot{}
	}
	if s := h.p.Load(); s != nil {
		return *s
	}
	return Snapshot{}
}

// Store Полная замена снапшота.
func (h *Holder) Store(s Snapshot) { h.p.Store(&s) }
