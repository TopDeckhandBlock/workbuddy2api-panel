// wafip.go WAF IP перехват уровня fail-fast Стейт-машина (ТЗ waf-ip-failfast）。
//
// Фон (fork-scan-absorb T-1 / BulidH фактически измерено):WAF 403 блокируется на выходе шлюза IP а не
// Аккаунт —3 аккаунтов 1 за секунды всё 403。Существующий ErrWafBlock мягкое охлаждение на уровне аккаунта (wafCooldownBase
// ограниченный бэкофф от) в IP уровня блокировки недостаточно: ротация умножит один клиентский запрос MaxRotate раз,
// единый выход IP Дальнейшие запросы к апстриму только усилят риск-контроль.
//
// Критерий:ErrWafBlock подсчет по нескольким номерам в коротком окне на базе —wafIPWindow（60s скользящего окна) внутри
// ≥ wafIPThreshold шт.**Разное** UID Подряд хиты WAF 403 → решение IP перехват уровня, активация до
// now+wafIPWindow。повторная обработка одного номера 403（случайная ошибка уровня аккаунта) никогда не триггерит: считаются только разные номера.
// Новые попадания в период активации не продлевают срок (консервативно: без активного зондирования, окно снимается естественно).
//
// оценка уровня принадлежности: поместить в server（Handler локально), а не pool——IP единственный потребитель статуса уровня —
// chatCompletions цикл ротации (продолжать ли ротацию),pool уровень учёта на аккаунт, кросс- UID Семантика
// не принадлежит ни одному аккаунту;server Уже есть прецедент состояния на уровне процесса degradeGate（mu+until В том же стиле).
// Мягкий кулдаун на уровне аккаунта учитывается как обычно (applyErrorPolicy неизменно),IP состояние уровня меняет только "продолжать ли
// ротация» — совместно не суммируется. Состояние в процессе, сброс при рестарте (окно 60s，стоимость пересоздания крайне низкая).
package server

import (
	"log"
	"sync"
	"time"
)

// wafIPWindow IP скользящее окно определения уровня + Длительность активации: попадания разных аккаунтов в окне WAF 403 при достижении порога
// определить IP Блокировка уровня, активируется на тот же срок (снимается автоматически по истечении).var только для тестовой инжекции короткого окна (в проде всегда 60s，
// ТЗ "напр. 60s скользящее окно»).
var wafIPWindow = 60 * time.Second

// wafIPThreshold Порог срабатывания: разные в окне UID при достижении значения активация. Взять 2——「минимум для "много номеров»
// Определение: повторные по одному номеру 403 Никогда не срабатывает (разовые на уровне аккаунта — в soft-cooldown), два разных аккаунта в 60s внутри подряд
// заблокирован (тот же выход IP）уже IP доказательство уровня (BulidH На практике 3 номер 1s Блокировать всё, порог 2 Более ранний стоп-лосс,
// на одну ротацию меньше).
const wafIPThreshold = 2

// wafIPGate WAF IP уровневый стейт-машина блокировки (Handler встроено, нулевое значение допустимо).
type wafIPGate struct {
	mu sync.Mutex
	hits map[string]time.Time // uid → последний раз WAF 403 момент (внутри окна решения, ленивая обрезка)
	until time.Time // IP Блокировка уровня активна до; нулевое значение = не активирован
}

// noteWaf зафиксировать для аккаунта WAF 403，после учета возврата IP активна ли блокировка уровня (вызывающая сторона на этом основании
// fail-fast Прервать ротацию, приоритет над rotateBackoff бэкофф).
// - Уже активирован (now < until）：Без продления, без учета (внутри окна без сброса — консервативное естественное снятие)→ true；
// - не активирован: запись hits[uid]=now（Повторные попадания одного номера с перезаписью не суммируются, критерий — "число разных номеров»),
// отсечь просроченные попадания вне окна; разные UID Количество достигает wafIPThreshold → Активировать до now+wafIPWindow
// （Залогировать одну запись WARN для наблюдения), сброс окна детекции (после снятия требуется новое попадание для решения, без учета старого).
func (g *wafIPGate) noteWaf(uid string) bool {
	now := time.Now()
	g.mu.Lock()
	defer g.mu.Unlock()
	if now.Before(g.until) {
		return true // Новое срабатывание в период активации: без продления (семантика естественного снятия, ТЗ п. 3 шт.)
	}
	if g.hits == nil {
		g.hits = map[string]time.Time{}
	}
	g.hits[uid] = now
	for u, t := range g.hits {
		if now.Sub(t) > wafIPWindow {
			delete(g.hits, u)
		}
	}
	if len(g.hits) >= wafIPThreshold {
		g.until = now.Add(wafIPWindow)
		log.Printf("WARN: [server] waf ip-level block: %d accounts hit waf 403 within %s, rotate fail-fast until %s", len(g.hits), wafIPWindow, g.until.Format(time.RFC3339))
		g.hits = map[string]time.Time{}
		return true
	}
	return false
}

// active отчет IP активен ли перехват уровня (различение текста ошибки на конце IP Уровень/формулировка уровня аккаунта).
func (g *wafIPGate) active() bool {
	g.mu.Lock()
	defer g.mu.Unlock()
	return time.Now().Before(g.until)
}
