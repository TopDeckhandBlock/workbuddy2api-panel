// понижение веса при серии поражений (issue #114）：NoteFailures Счетчик + При достижении порога — временный вывод из пула + NoteSuccess Сброс в ноль.
// и кулдаун/circuit-breaker "при параллельном берётся больший, без суммирования» обеспечивает entry.healthy параллельный OR естественно гарантирует
// （Три дедлайна — ИЛИ, любой не истёк — выбор невозможен, действует самый дальний — см. entry.degradeUntil комментарий).
package pool

import "time"

// NoteFailures Записать один "нештрафной фейл» (issue #114 вход подачи резерва при серии неудач):
// consecutiveFails++，достигнуто degradeThreshold Триггер понижения приоритета (degradeUntil = now +
// Длительность понижения, счетчик сбрасывается для нового цикла — аналогично recordBreakerFailureLocked философия).
// **Уже в периоде понижения приоритета**（degradeUntil не истёк) повторное достижение порога: без продления, без удвоения (защита от ретраев пользователя
// Накапливает понижение веса, и CooldownSoftRate fallback-проверка той же философии) — сброс счетчика, после истечения — пропуск
// Нужно снова набрать порог последовательных неудач для повторного понижения. Успех (NoteSuccess）обнулить счётчик и сбросить дедлайн понижения приоритета.
//
// кому подавать:ErrClient（неизвестно 4xx，applyErrorPolicy default только смена номера без штрафа) и транспортным уровнем
// сбой (handler Ветка сетевого джиттера, также только смена аккаунта без штрафа) — оба случая "сбой с неизвестной причиной»,
// Именно целевая форма страховки от серии неудач. Ошибка с авторитетной классификацией (429/WAF/402/5xx/12153/11140/11102）
// У каждого — "штраф с известной причиной» (кулдаун/Circuit Breaker/Отключено/негативный кэш), не подавать в этот счётчик — штраф уже есть,
// Повторная подача серии неудач — двойной штраф (по ТЗ: при наличии двух механизмов берется больший, без суммирования).
func (p *Pool) NoteFailures(uid string) {
	p.mu.Lock()
	defer p.mu.Unlock()
	e, ok := p.byUID[uid]
	if !ok {
		return
	}
	e.consecutiveFails++
	if e.consecutiveFails < p.degradeThreshold {
		p.dirty.Store(true)
		return
	}
	e.consecutiveFails = 0
	if !e.degradeUntil.IsZero() && time.Now().Before(e.degradeUntil) {
		// достижение порога серии поражений в период понижения приоритета: не продлевать (семантика выбора большего healthy гарантия OR). Счётчик
		// уже сброшено — после истечения и разблокировки требуется заново набрать порог неудач подряд для повторного понижения.
		p.dirty.Store(true)
		return
	}
	e.degradeUntil = time.Now().Add(p.degradeDurationLocked())
	p.dirty.Store(true)
}

// degradeDurationLocked Вернуть длительность понижения приоритета (текущая реализация — фикс. degradeCooldown，Ограничить до
// [defaultDegradeCooldown, degradeCooldownMax]）。Без экспоненциального повышения: счётчик срабатываний при достижении порога
// обнуление, без сохранения истории срабатываний, уровень невыводим; фиксированной длительности достаточно для "временного вывода из пула на некоторое время»
// семантика (реально persistently битый номер в следующем раунде 5 ещё одно понижение в серии неудач). Вызывающая сторона должна уже иметь p.mu。
func (p *Pool) degradeDurationLocked() time.Duration {
	d := p.degradeCooldown
	if d <= 0 {
		d = defaultDegradeCooldown
	}
	max := p.degradeCooldownMax
	if max <= 0 {
		max = defaultDegradeCooldownMax
	}
	if d > max {
		d = max
	}
	return d
}
